        static void AssertBits(string policy, string column, long[] baked, Func<int, double> actual)
        {
            for (int i = 0; i < CorridorStages; i++)
            {
                long expected = baked[i];
                double value = actual(i);
                long got = BitConverter.DoubleToInt64Bits(value);

                if (got == expected) continue;

                Assert.Fail(string.Format(
                    "[{0}] stage {1} {2}: 굳힌 비트 {3} (= {4:R}) 대 실측 {5} (= {6:R}).\n"
                    + "조율 코리더가 움직였다. 재설계가 st1~30을 건드리지 않는다는 약속이 "
                    + "깨졌거나(기대 티어 곡선이 st30에서 샌다), 코리더를 의도적으로 다시 "
                    + "연 것이다. 후자라면 이 파일의 배열을 함께 재생성하고 그 사실을 "
                    + "커밋에 남겨라.",
                    policy, i + 1, column,
                    expected, BitConverter.Int64BitsToDouble(expected), got, value));
            }
        }

        /**
         * @brief 곡선 추종(보석 무제한) 세계의 코리더.
         *
         * 밴드 천장을 재는 쪽이다. 전직이 이 구간에 구조적으로 없으므로
         * (해금 Lv.30 = 실측 st37) 재설계가 이 서른 줄을 지나가면 안 된다.
         */
        [Test]
        public void Corridor_IsBitIdenticalForTheLeadPlayer()
        {
            var rows = StageSimulation.Run(CorridorStages, FieldFromAssets());

            Assert.AreEqual(CorridorStages, rows.Count, "코리더의 행 수가 바뀌었다");

            AssertBits("Default", "BossMargin", DefaultBossMargin, i => rows[i].BossMargin);
            AssertBits("Default", "SurvivalMargin", DefaultSurvivalMargin, i => rows[i].SurvivalMargin);
            AssertBits("Default", "MobSeconds", DefaultMobSeconds, i => rows[i].MobSeconds);
            AssertBits("Default", "BossKillSeconds", DefaultBossKillSeconds, i => rows[i].BossKillSeconds);
        }

        /**
         * @brief 보석 하한(일일 0회) 세계의 코리더. 밴드 바닥을 재는 쪽이다.
         *
         * st1~12는 위와 값이 같고 st13부터 갈린다 - 장비 등급업 보석이 하한
         * 쪽에서 막히기 시작하는 자리다. 한쪽만 구우면 그 갈림이 검사되지 않는다.
         */
        [Test]
        public void Corridor_IsBitIdenticalForTheGemFloorPlayer()
        {
            var rows = StageSimulation.Run(CorridorStages, FieldFromAssets(),
                new StageSimulation.Policy { GemsFromQuestsOnly = true });

            Assert.AreEqual(CorridorStages, rows.Count, "코리더의 행 수가 바뀌었다");

            AssertBits("GemFloor", "BossMargin", GemFloorBossMargin, i => rows[i].BossMargin);
            AssertBits("GemFloor", "SurvivalMargin", GemFloorSurvivalMargin, i => rows[i].SurvivalMargin);
            AssertBits("GemFloor", "MobSeconds", GemFloorMobSeconds, i => rows[i].MobSeconds);
            AssertBits("GemFloor", "BossKillSeconds", GemFloorBossKillSeconds, i => rows[i].BossKillSeconds);
        }

        /**
         * @brief 굳힌 두 표가 **실제로 다르다.**
         *
         * 자기 검사다. 두 정책의 배열을 같은 실행에서 굽다가 한쪽을 복사해
         * 붙이면 위 두 검사는 통과하면서 하한 세계를 아무도 안 재게 된다 -
         * 16단계가 "샀는가"만 보는 자로 죽은 버튼을 놓친 것과 같은 종류의
         * 구멍이다.
         */
        [Test]
        public void TheTwoBakedWorlds_AreActuallyDifferent()
        {
            int differences = 0;
            for (int i = 0; i < CorridorStages; i++)
                if (DefaultBossMargin[i] != GemFloorBossMargin[i]) differences++;

            Assert.Greater(differences, 0,
                "두 정책의 굳힌 여유가 서른 줄 전부 같다 - 한쪽을 복사해 붙였다");

            // st1~12는 같아야 한다. 장비 등급업이 하한 쪽에서 막히기 전이다
            for (int i = 0; i < 12; i++)
                Assert.AreEqual(DefaultBossMargin[i], GemFloorBossMargin[i], string.Format(
                    "stage {0}: 두 세계가 벌써 갈렸다 - 보석이 코리더 초입부터 병목이 됐다",
                    i + 1));
        }

        /**
         * @brief 코리더에 전직이 **구조적으로** 없다. 2단계에 근거가 바뀌었다.
         *
         * ## 1.6단계에는 "보정이 곱셈 항등원"이었다
         *
         * 그때 `EvolutionCompensation(1..30)`이 `Math.Pow(1.0, 0.42)`라 정확히
         * 1.0이었고, 그 항등성이 위 비트 동일의 이유였다. 검사도 그 값의
         * 비트를 봤다 - 1.0000000001을 곱하면 코리더가 움직이기 때문이다.
         *
         * ## 2단계에 그 항이 **사라졌다**
         *
         * 지수 0.00이 승인되면서 `BossHealthForStage`에서 곱 자체를 지웠다.
         * 그래서 이제 잴 값이 없다 - 곱하지 않는 것은 1.0을 곱하는 것보다
         * 강한 보장이고, "1.0에 가까운 값"이 새어 들어올 경로가 아예 없다.
         *
         * 남은 근거는 하나다: **첫 문이 st30 클리어**라 코리더 서른 줄이 문을
         * 한 번도 지나지 않는다. 그것을 여기서 못 박는다 - 게이트가 앞으로
         * 내려오면 위의 넷보다 이 검사가 먼저 실패해야 원인이 보인다.
         */
        [Test]
        public void CorridorHasNoPromotionAtAll()
        {
            for (int stage = 1; stage <= CorridorStages; stage++)
            {
                Assert.AreEqual(0, PromotionTrialCatalog.TierAtFrontier(stage), string.Format(
                    "stage {0}: 지나온 문이 {1}개다 - 코리더에 귀문이 새어 들어왔다",
                    stage, PromotionTrialCatalog.TierAtFrontier(stage)));

                Assert.AreEqual(0, EvolutionCurve.ExpectedTierAtStage(stage), string.Format(
                    "stage {0}: 기대 티어가 {1}이다", stage, EvolutionCurve.ExpectedTierAtStage(stage)));

                // 배수도 정확히 1이다. 곱해질 값이 항등원이라는 사실은
                // 여전히 필요하다 - 티어 0의 배수가 1.0000001이면 코리더가 움직인다
                Assert.AreEqual(BitConverter.DoubleToInt64Bits(1d),
                    BitConverter.DoubleToInt64Bits(EvolutionCurve.ExpectedPowerAtStage(stage)),
                    string.Format("stage {0}: 티어 0의 배수가 정확히 1이 아니다", stage));
            }

            Assert.GreaterOrEqual(PromotionTrialCatalog.GateStages[0], CorridorStages,
                "첫 귀문이 코리더 안으로 들어왔다 - 위 비트 표를 다시 구워야 한다");
        }
