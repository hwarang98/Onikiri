        static void AssertBits(string policy, string column, long[] baked, Func<int, double> actual)
        {
            for (int i = 0; i < CorridorStages; i++)
            {
                long expected = baked[i];
                double value = actual(i);
                long got = BitConverter.DoubleToInt64Bits(value);

                if (got == expected) continue;

                Assert.Fail(string.Format(
                    "[{0}] stage {1} {2}: 굳힌 비트 {3} (= {4:R}) 대 실측 {5} (= {6:R}).\n"
                    + "조율 코리더가 움직였다. 재설계가 st1~30을 건드리지 않는다는 약속이 "
                    + "깨졌거나(기대 티어 곡선이 st30에서 샌다), 코리더를 의도적으로 다시 "
                    + "연 것이다. 후자라면 이 파일의 배열을 함께 재생성하고 그 사실을 "
                    + "커밋에 남겨라.",
                    policy, i + 1, column,
                    expected, BitConverter.Int64BitsToDouble(expected), got, value));
            }
        }

