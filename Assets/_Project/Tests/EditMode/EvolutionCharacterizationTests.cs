         * 밴드 천장을 재는 쪽이다. 전직이 이 구간에 구조적으로 없으므로
         * (해금 Lv.30 = 실측 st37) 재설계가 이 서른 줄을 지나가면 안 된다.
         */
        [Test]
        public void Corridor_IsBitIdenticalForTheLeadPlayer()
        {
            var rows = StageSimulation.Run(CorridorStages, FieldFromAssets());

            Assert.AreEqual(CorridorStages, rows.Count, "코리더의 행 수가 바뀌었다");

            AssertBits("Default", "BossMargin", DefaultBossMargin, i => rows[i].BossMargin);
            AssertBits("Default", "SurvivalMargin", DefaultSurvivalMargin, i => rows[i].SurvivalMargin);
            AssertBits("Default", "MobSeconds", DefaultMobSeconds, i => rows[i].MobSeconds);
            AssertBits("Default", "BossKillSeconds", DefaultBossKillSeconds, i => rows[i].BossKillSeconds);
        }

