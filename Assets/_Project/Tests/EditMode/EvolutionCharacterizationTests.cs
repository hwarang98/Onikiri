     * @brief 승급·전직 재설계 **직전**의 조율 코리더를 비트로 굳힌 특성화 검사.
     *
     * ## 왜 허용 오차가 아니라 원시 비트인가
     *
     * 재설계가 약속하는 것은 "코리더가 거의 안 움직인다"가 아니라 **한 비트도
     * 안 움직인다**이다. 그 약속은 계수가 아니라 구조에서 온다 - 첫 귀문이
     * `st30 클리어`라 `ExpectedTierAtStage(30) = 0`이 유지되고, 그러면 이
     * 구간의 전직 배수가 정확히 1.0이라 곱셈이 항등이 된다. 시뮬레이션은
     * 결정론이므로 항등원을 곱한 결과는 비트까지 같아야 한다.
     *
     * **2단계에는 그 곱조차 사라졌다** - 보정항 자체를 지웠으므로(지수 0.00
     * 승인) 코리더가 지나는 곱이 하나 줄었다. 아래 표가 그 변경 뒤에도
     * 그대로라는 것이 이 파일의 이번 판 성과다.
     *
     * 상대오차를 쓰면 그 약속이 "1e-9 안에서 같다"로 조용히 약해지고, 그 폭
     * 안에는 **기대 티어 곡선이 st30에서 한 칸 새는** 실수가 통째로 들어간다.
     * 여유 1.44가 1.4400000003이 되는 변경은 오차가 아니라 사고다.
     *
     * ## 두 정책을 다 굽는 이유
     *
     * 밴드가 두 끝을 재기 때문이다(`Policy.GemsFromQuestsOnly` 주석). 코리더
     * 안에서는 두 세계가 거의 같지만 st13부터 갈린다 - 장비 등급업 보석이
     * 하한 쪽에서 막히기 시작하는 자리다. 한쪽만 구우면 그 갈림이 검사되지
     * 않는다.
     *
     * ## 이 파일은 재설계가 끝나면 지우지 않는다
     *
     * 32~56단계가 코리더를 여러 번 "건드리지 않았다"고 적었지만, 그 주장을
     * 비트로 붙잡아 둔 검사는 없었다. 이 파일이 그 자리다 - 다음 스텝이
     * 코리더를 의도적으로 다시 열 때는 **여기 숫자를 함께 고치는 것**이
     * 절차가 된다.
     */
