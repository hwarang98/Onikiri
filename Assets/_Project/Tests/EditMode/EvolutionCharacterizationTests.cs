        [Test]
        public void TheTwoBakedWorlds_AreActuallyDifferent()
        {
            int differences = 0;
            for (int i = 0; i < CorridorStages; i++)
                if (DefaultBossMargin[i] != GemFloorBossMargin[i]) differences++;

            Assert.Greater(differences, 0,
                "두 정책의 굳힌 여유가 서른 줄 전부 같다 - 한쪽을 복사해 붙였다");

            // st1~12는 같아야 한다. 장비 등급업이 하한 쪽에서 막히기 전이다
            for (int i = 0; i < 12; i++)
                Assert.AreEqual(DefaultBossMargin[i], GemFloorBossMargin[i], string.Format(
                    "stage {0}: 두 세계가 벌써 갈렸다 - 보석이 코리더 초입부터 병목이 됐다",
                    i + 1));
