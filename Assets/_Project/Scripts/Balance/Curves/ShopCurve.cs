namespace Onikiri.Progression
{
    /**
     * @brief 상점 탭과 **스킬 뽑기 배너**가 서는 칸.
     *
     * ## 왜 요도에서 떼어내는가
     *
     * 47단계까지 `GachaCurve.UnlockStage`가 `YodoCurve.UnlockStage`(st41)를
     * 가리켰고, 그 한 값이 상점 탭·요도 배너·스킬 배너·가챠 몫 오의의 골드
     * 앵커를 한꺼번에 잠갔다. 배너가 하나뿐일 때는 그것이 맞았다 - 상점이
     * 열리는 칸이 곧 그 배너가 열리는 칸이었다.
     *
     * 배너가 둘이 되면서 그 등호가 깨진다. 두 배너가 **다른 것을 판다**:
     *
     *     요도 배너   파워를 판다. st41 가속 구간의 곡선과 얽혀 있어 못 옮긴다
     *     스킬 배너   폭과 시간을 판다. 파워가 아니므로 코리더 안에 세워도 된다
     *
     * 스킬 뽑기를 st41에 두면 무과금이 이 축에 닿는 시점이 게임의 절반이
     * 지나서다. 뽑기가 파는 것이 "고를 것"인데 고를 것이 생기는 때가 이미
     * 다 고르고 난 뒤인 셈이다.
     *
     * ## 왜 하필 st14인가
     *
     * 코리더(st1~30)의 사건 배치에서 빈 칸이다:
     *
     *     st8  연참(자리+1)   st12 혈파동(선택+1)   **st14 상점**
     *     st15 일섬(자리+1)   st18 낙혈(선택+1)     st21 귀참(자리+1)
     *
     * 두 칸 간격이 유지되고 사건의 종류(해금/선택/상점)가 갈려 겹쳐 읽히지
     * 않는다. st13이나 st16으로 밀면 앞뒤 사건과 한 칸 붙어 둘 중 하나가
     * 안 읽힌다.
     *
     * ## 여기 없는 것
     *
     * 확률표·가격·일일 무료·★4 소프트 천장은 **여전히 요도 배너와 공유한다**
     * (SkillGachaCurve 머리 주석). 갈리는 것은 이 해금 칸과 ★5 하드 천장
     * 둘뿐이고, 그 둘만 갈리는 이유가 위에 적힌 "다른 것을 판다"이다.
     */
    public static class ShopCurve
    {
        /**
         * @brief 상점 탭 + 스킬 뽑기 배너가 열리는 최전선.
         *
         * 가챠 몫 오의의 `SkillSpec.UnlockStage`도 이 값을 쓴다. 그것은 열리는
         * 자리가 아니라 **골드 비용의 기준점**인데(SkillSpec.UnlockStage 주석),
         * 뽑기로 열리는 오의의 "열리는 스테이지"는 확률이라 정해지지 않으므로
         * **가장 이른 획득 가능 시점**을 쓴다.
         *
         * st41에서 st14로 내려오면서 그 앵커가 실제로 움직인다 - 골드는
         * 스테이지마다 x1.72로 자라므로 스물일곱 칸이면 규모가 통째로 다르다.
         * `Skills_HaveTheSameGoldEfficiencyAtUnlock`이 새 기준으로 다시 잰다.
         */
        public const int UnlockStage = 14;

        public static bool IsUnlockedAt(int stage)
        {
            return stage >= UnlockStage;
        }
    }
}
