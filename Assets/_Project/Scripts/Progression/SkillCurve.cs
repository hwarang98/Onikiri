using System;

namespace Onikiri.Progression
{
    /**
     * @brief 스킬 배율 강화 곡선. 세 스킬이 **같은 곡선을 공유한다.**
     *
     * ## 왜 하나인가
     *
     * 스킬마다 곡선을 따로 두면 축이 셋이 아니라 셋 x 곡선 계수가 되고, 그중
     * 하나만 나쁘게 잡히면 그 스킬은 함정이 된다 - 화면에서는 세 줄이 똑같이
     * 생겼는데 하나만 사면 손해인 상태다. 8단계 공격속도가 딱 그 모양이었다.
     *
     * 스킬 사이의 차이는 곡선이 아니라 **기본 배율과 쿨다운**이 만든다
     * (SkillCatalog). 그 둘의 비 `배율/쿨다운`이 이 축이 DPS에 기여하는 전부라,
     * 곡선을 공유해도 세 스킬은 서로 다른 무게를 갖는다.
     *
     * ## 쿨다운은 성장 축이 아니다
     *
     * 레벨업은 **배율만** 올린다. 쿨다운을 성장 축으로 두면 9단계 공격속도와
     * 같은 벽에 부딪힌다 - 시전 간격이 애니메이션 길이 아래로 내려갈 수 없어서
     * 어느 지점부터 레벨이 값을 잃고, 그때 상한을 어디에 둘지가 다시 아트에
     * 묶인다. 배율은 숫자일 뿐이라 그런 한계가 없다.
     *
     * ## 상한이 구조적 요구인 이유
     *
     * 스킬 DPS는 자동 공격의 **초당 횟수에 더해지는** 항이다(CombatStats).
     *
     *     DPS = 공격력 x (공격속도 + 스킬 환산 초당횟수) x 치명타
     *
     * 공격속도는 아트가 정한 상한(3.88)에서 멈추는데 스킬 항에 상한이 없으면,
     * 배율이 곱연산으로 자라는 동안 이 항이 괄호 전체를 지배하게 된다. 그러면
     * DPS = 공격력 x 스킬항 이 되고 **둘 다 공격력 강화 레벨을 따라 자라므로
     * DPS가 레벨의 제곱으로 자란다.** 보스 체력 곡선은 어떤 램프로도 그것을
     * 따라갈 수 없다.
     *
     * 그래서 상한은 밸런스 손잡이가 아니라 구조적 요구다 - 골드 획득 축이
     * 같은 이유로 상한을 갖는 것과 같다(GoldGainCurve).
     */
    public static class SkillCurve
    {
        /**
         * @brief 레벨당 배율. 공격력 강화와 **같은 값**이다.
         *
         * 같아야 하는 이유는 비용 증가율이 서로 다르기 때문이다. 두 축의 효율
         * 비율은 (값 증가율 / 비용 증가율)의 레벨 거듭제곱으로 벌어지는데,
         * 값 쪽까지 다르면 그 벌어짐이 두 계수의 곱이 되어 어느 쪽이 원인인지
         * 읽을 수 없게 된다. 아래 CostGrowth 하나만 다르게 두고 그 하나로
         * 이 축의 수명을 정한다.
         */
        public const double Step = 1.12d;

        /**
         * @brief 배율 상한 = 기본 배율 x 이 값.
         *
         * 세 스킬을 다 채운 상태의 환산 초당횟수가 2.40이 되도록 잡았다. 공격속도
         * 상한 3.88보다 작다 - **자동 공격이 여전히 주력이고 스킬이 얹히는
         * 것**이라는 관계가 그 부등호에 들어 있다. 뒤집히면 공격속도 축이
         * 장식이 되는데, 상한에 닿은 축을 더 무의미하게 만드는 것은 새 축이
         * 해도 되는 일이 아니다.
         *
         * ## 왜 8이 아니라 3.2인가 - 첫 칸의 체감
         *
         * 처음에 x8로 잡고 기본 배율을 그만큼 작게 뒀다(합 0.30). 상한에서의
         * 총량은 같았지만 **해금 직후 한 칸이 DPS를 0.2%밖에 못 올렸다.**
         *
         * 이유는 산수다. 가산 항의 한 칸이 총 DPS를 올리는 폭은
         *
         *     (그 스킬의 DPS 몫) x (Step - 1)
         *
         * 인데, 상한 비가 클수록 기본값이 작아야 하고 기본값이 작으면 해금 시점의
         * 몫도 작다. 몫 1.8%에 Step 1.12면 0.2%다 - 16단계가 스탯 포인트에서
         * 잡은 "눌러도 숫자가 안 움직이는 버튼"과 같은 상태다.
         *
         * 상한 비를 8에서 3.2로 줄이고 기본 배율을 2.5배로 키우면(합 0.75)
         * 해금 시 몫이 4.4%가 되어 첫 칸이 0.5%, 상한 근처의 칸은 1.1%가 된다.
         * 총량(2.40)은 그대로다 - 옮긴 것은 **곡선의 어디에 무게를 두는가**뿐이다.
         *
         * 남는 대가는 칸 수다. 축당 12레벨이라 여섯 축의 수십~백 레벨보다 훨씬
         * 짧다. 골드 획득 축(13레벨)과 같은 급이고, 상한이 있는 축은 원래 그렇다.
         */
        public const double CeilingRatio = 3.2d;

        /**
         * @brief 레벨당 비용 배수. **여섯 축(1.15)보다 가파르다.**
         *
         * 1.15로 두면 이 축이 상한까지 몇 스테이지 만에 밀려 올라간다. 스킬의
         * %DPS 기여는 괄호 안 비중이 커질수록 **포화**하는데(더할수록 한 칸의
         * 상대 몫이 작아진다), 비용이 같은 속도로만 오르면 그 포화가 구매를
         * 멈출 만큼 빠르지 않기 때문이다.
         *
         * ## 왜 1.30까지 올렸는가 - 상한 있는 축은 반드시 빨리 팔린다
         *
         * 처음에 1.18로 잡고 시뮬레이션을 돌리자 스킬 하나가 **해금 3스테이지
         * 만에 상한**에 닿았다. 21단계의 골드 획득 축이 해금 즉시 상한에 닿은
         * 것과 같은 현상이고, 원인도 같다.
         *
         * 이 축이 한 스테이지에 오르는 레벨 수는 두 힘의 합이다.
         *
         *     수입 성장          스테이지당 x1.72
         *     경쟁 축의 비용 상승 공격력이 스테이지당 4레벨 -> x1.15^4 = x1.75
         *     합                 x3.0  ->  ln(3.0)/ln(비용 증가율) 레벨/스테이지
         *
         * 1.18이면 6.6레벨/스테이지라 축 하나가 3스테이지에 소진된다. 1.45면
         * 2.9레벨/스테이지가 되어 12레벨이 약 4스테이지에 걸치고, 세 스킬이
         * Lv.10/15/20에 차례로 열리므로 st8~st25에 살 것이 계속 있다.
         *
         * 더 올리지 않은 이유는 마지막 칸의 값이다. 1.45^11 = x60이라 상한
         * 직전 한 칸이 첫 칸의 예순 배인데, 그보다 가팔라지면 "다 왔는데 마지막
         * 하나가 유독 멀다"가 된다.
         */
        public const double CostGrowth = 1.45d;

        /**
         * @brief 첫 비용 = (기본 배율 / 쿨다운) x 이 값.
         *
         * 스킬마다 비용을 손으로 적지 않는 이유는, 그러면 셋 중 하나가 조용히
         * 나쁜 거래가 되기 때문이다. 이 축이 DPS에 기여하는 것은 오직 **초당
         * 환산 기여**(배율/쿨다운)이므로, 비용을 그 값에 비례시키면 세 스킬의
         * 골드당 효율이 처음부터 같다 - 어느 것을 먼저 올려도 손해가 아니다.
         *
         * 크기는 시뮬레이션에서 잡았다. 이보다 싸면 해금과 거의 동시에 상한에
         * 닿아(골드 획득 축이 21단계에 그랬다) 남은 구간이 전부 MASTER가 되고,
         * 비싸면 구매 정책이 여섯 축을 계속 우선해 화면에서 죽은 줄이 된다.
         *
         * 처음에 600으로 잡았다가 150으로 내렸다. **해금 직후 첫 칸이 그 시점
         * 파밍 스물네 마리 값이었기 때문이다.** 새로 열린 시스템의 첫 줄이 두
         * 스테이지를 모아야 눌리는 버튼이면, 열어준 것이 화면이 아니라 빚이다.
         * 150이면 다섯 마리 값이라 그 스테이지 안에서 눌린다.
         */
        public const double CostPerRate = 150d;

        /** 상한을 무시한 배율. 형태를 보는 지표가 쓴다 */
        public static double MultiplierAtLevel(double baseMultiplier, int level)
        {
            return baseMultiplier * Math.Pow(Step, Math.Max(0, level - 1));
        }

        /** 게임이 실제로 쓰는 배율. 상한에서 멈춘다 */
        public static double CappedMultiplierAtLevel(double baseMultiplier, int level)
        {
            return Math.Min(baseMultiplier * CeilingRatio, MultiplierAtLevel(baseMultiplier, level));
        }

        /** 이 스킬의 배율 상한 */
        public static double CeilingFor(double baseMultiplier)
        {
            return baseMultiplier * CeilingRatio;
        }

        /**
         * @brief 상한에 처음 닿는 레벨. UpgradeTrack의 maxLevel로 쓴다.
         *
         * 기본 배율에 무관하다 - 상한이 배율의 **비**로 정의돼 있어서 셋 다
         * 같은 레벨에서 멈춘다. 그것이 곡선을 공유하는 이유이기도 하다.
         */
        public static int MaxLevel
        {
            get
            {
                int level = 1 + (int)Math.Ceiling(Math.Log(CeilingRatio) / Math.Log(Step));
                return Math.Max(1, level);
            }
        }

        public static double CostAtLevel(double baseCost, int level)
        {
            return baseCost * Math.Pow(CostGrowth, Math.Max(0, level - 1));
        }
    }
}
